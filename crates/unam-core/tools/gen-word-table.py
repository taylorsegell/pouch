#!/usr/bin/env python3
"""Generate and check the slugify word table (milestone M2 plan P3, P23).

Hermes `slugify_skill_name` deletes every character that is not Python `\\w`
or `-`. Rust's `char::is_alphanumeric` is a superset of Python `\\w` (minus
`_`); the surplus code points are listed in `crates/unam-core/src/bundle/
word_table.rs` (constant `NOT_WORD`) so the Rust predicate matches Python.

Python alone cannot compute Rust's ranges, so the Rust side is the committed
data file `crates/unam-core/tools/rust-word-ranges.txt`.

Modes (exactly one per run; usage errors exit 2):
  --write-rust-ranges  needs rustc (exit 4 without it); writes the data file
  --write              writes word_table.rs from the data file and this Python
  --check              Python only; exit 0 OK, 1 FAIL, 3 Unicode-data DRIFT
  --check-rust         needs rustc (exit 4 without it); exit 0 OK, 1 FAIL, 3 DRIFT

Standard library only; no network; every path is resolved from this file.
"""

import argparse
import bisect
import difflib
import pathlib
import re
import subprocess
import sys
import tempfile
import unicodedata

TOOLS = pathlib.Path(__file__).resolve().parent
CRATE = TOOLS.parent
DATA_FILE = TOOLS / "rust-word-ranges.txt"
TABLE_FILE = CRATE / "src" / "bundle" / "word_table.rs"

DATA_REL = "crates/unam-core/tools/rust-word-ranges.txt"
SCRIPT_REL = "crates/unam-core/tools/gen-word-table.py"

HEADER_GENERATED = (
    "# @generated by crates/unam-core/tools/gen-word-table.py --write-rust-ranges."
    " Do not edit by hand."
)
HEADER_RUSTC = "# rustc: "
HEADER_UNICODE = "# rust-unicode: "
HEADER_DEFINITION = (
    "# definition: maximal ranges of Unicode scalar values c where"
    " c == '_' || c.is_alphanumeric()"
)

MAX_CP = 0x10FFFF
SURROGATE_LO = 0xD800
SURROGATE_HI = 0xDFFF

EXIT_OK = 0
EXIT_FAIL = 1
EXIT_DRIFT = 3
EXIT_NO_RUSTC = 4

RUST_PRINTER = r"""
fn main() {
    let (a, b, c) = char::UNICODE_VERSION;
    println!("# rust-unicode: {a}.{b}.{c}");
    let mut start: Option<u32> = None;
    let mut prev: u32 = 0;
    for cp in 0..=0x10FFFFu32 {
        let word = match char::from_u32(cp) {
            Some(c) => c == '_' || c.is_alphanumeric(),
            None => false,
        };
        if word {
            if start.is_none() {
                start = Some(cp);
            }
            prev = cp;
        } else if let Some(s) = start.take() {
            println!("{:04X} {:04X}", s, prev);
        }
    }
    if let Some(s) = start {
        println!("{:04X} {:04X}", s, prev);
    }
}
"""

RANGE_LINE = re.compile(r"^([0-9A-F]{4,6}) ([0-9A-F]{4,6})$")


class DataError(Exception):
    """The data file is malformed."""


def python_version():
    v = sys.version_info
    return f"{v.major}.{v.minor}.{v.micro}"


def rustc_version():
    """`rustc --version` output, or None when rustc is not on PATH."""
    try:
        out = subprocess.run(
            ["rustc", "--version"], capture_output=True, text=True, check=True
        )
    except (FileNotFoundError, subprocess.CalledProcessError):
        return None
    return out.stdout.strip()


def run_rust_printer():
    """Build and run the Rust range printer; returns (rust_unicode, ranges)."""
    with tempfile.TemporaryDirectory() as tmp:
        src = pathlib.Path(tmp) / "printer.rs"
        exe = pathlib.Path(tmp) / "printer"
        src.write_text(RUST_PRINTER, encoding="utf-8")
        subprocess.run(
            ["rustc", "-O", "--edition", "2021", "-o", str(exe), str(src)],
            check=True,
            capture_output=True,
            text=True,
        )
        out = subprocess.run([str(exe)], check=True, capture_output=True, text=True)
    lines = out.stdout.splitlines()
    if not lines or not lines[0].startswith(HEADER_UNICODE):
        raise DataError("the Rust printer did not print its Unicode version")
    rust_unicode = lines[0][len(HEADER_UNICODE):]
    ranges = parse_ranges(lines[1:])
    return rust_unicode, ranges


def parse_ranges(lines):
    """Parse and validate range lines (ascending, disjoint, maximal)."""
    ranges = []
    for n, line in enumerate(lines, 1):
        m = RANGE_LINE.match(line)
        if not m:
            raise DataError(f"range line {n} is malformed: {line!r}")
        s, e = int(m.group(1), 16), int(m.group(2), 16)
        if s > e or e > MAX_CP:
            raise DataError(f"range line {n} is out of order or out of bounds: {line!r}")
        if s <= SURROGATE_HI and e >= SURROGATE_LO:
            raise DataError(f"range line {n} touches the surrogate gap: {line!r}")
        if ranges and s <= ranges[-1][1] + 1:
            raise DataError(
                f"range line {n} is not ascending, disjoint, and non-adjacent: {line!r}"
            )
        ranges.append((s, e))
    if not ranges:
        raise DataError("no ranges")
    return ranges


def read_data_file():
    """Returns (rustc, rust_unicode, ranges, range_lines)."""
    if not DATA_FILE.exists():
        raise DataError(f"{DATA_REL} does not exist; run --write-rust-ranges")
    lines = DATA_FILE.read_text(encoding="utf-8").splitlines()
    if len(lines) < 5:
        raise DataError("the data file is too short")
    if lines[0] != HEADER_GENERATED:
        raise DataError("header line 1 is not the generated marker")
    if not lines[1].startswith(HEADER_RUSTC) or len(lines[1]) == len(HEADER_RUSTC):
        raise DataError("header line 2 is not `# rustc: ...`")
    if not lines[2].startswith(HEADER_UNICODE) or len(lines[2]) == len(HEADER_UNICODE):
        raise DataError("header line 3 is not `# rust-unicode: ...`")
    if lines[3] != HEADER_DEFINITION:
        raise DataError("header line 4 is not the definition line")
    rustc = lines[1][len(HEADER_RUSTC):]
    rust_unicode = lines[2][len(HEADER_UNICODE):]
    ranges = parse_ranges(lines[4:])
    return rustc, rust_unicode, ranges, lines[4:]


def format_range(s, e):
    return f"{s:04X} {e:04X}"


def write_data_file(rustc, rust_unicode, ranges):
    lines = [
        HEADER_GENERATED,
        HEADER_RUSTC + rustc,
        HEADER_UNICODE + rust_unicode,
        HEADER_DEFINITION,
    ]
    lines.extend(format_range(s, e) for s, e in ranges)
    DATA_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def coalesce(cps):
    out = []
    for cp in cps:
        if out and cp == out[-1][1] + 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return [(s, e) for s, e in out]


def sweep(ranges):
    """Compare Python `\\w` with the Rust data file over every scalar value."""
    starts = [s for s, _ in ranges]
    word = re.compile(r"\w")
    py_only = 0
    cn_kept = 0
    excluded = []
    cats = {}
    for cp in range(MAX_CP + 1):
        if SURROGATE_LO <= cp <= SURROGATE_HI:
            continue
        ch = chr(cp)
        pyw = word.match(ch) is not None
        i = bisect.bisect_right(starts, cp) - 1
        inr = i >= 0 and ranges[i][0] <= cp <= ranges[i][1]
        if pyw and not inr:
            py_only += 1
        elif inr and not pyw:
            cat = unicodedata.category(ch)
            if cat == "Cn":
                cn_kept += 1
            else:
                excluded.append(cp)
                cats[cat] = cats.get(cat, 0) + 1
    return {
        "py_only": py_only,
        "cn_kept": cn_kept,
        "excluded": excluded,
        "ranges": coalesce(excluded),
        "cats": cats,
    }


def render_table(rustc, rust_unicode, result):
    cats = ", ".join(
        f"{c} {n}" for c, n in sorted(result["cats"].items(), key=lambda kv: (-kv[1], kv[0]))
    )
    lines = [
        f"// @generated by {SCRIPT_REL}. Do not edit by hand.",
        f"// Regenerate: python3 {SCRIPT_REL} --write",
        f"// Verify: python3 {SCRIPT_REL} --check",
        f"// Python: {python_version()}",
        f"// Unicode: {unicodedata.unidata_version}",
        f"// Rust data: {DATA_REL} ({rustc}, Unicode {rust_unicode})",
        f"// Excluded: {len(result['excluded'])} code points in"
        f" {len(result['ranges'])} ranges ({cats})",
        f"// Python-only code points (must be 0): {result['py_only']}",
        f"// Newer-Unicode letters kept as word characters (Cn in this Python):"
        f" {result['cn_kept']}",
        "",
        "pub(super) const NOT_WORD: &[(u32, u32)] = &[",
    ]
    lines.extend(f"    (0x{s:04X}, 0x{e:04X})," for s, e in result["ranges"])
    lines.append("];")
    return "\n".join(lines) + "\n"


def summary(rust_unicode, result):
    return (
        f"gen-word-table: python={python_version()} unicode={unicodedata.unidata_version}"
        f" rust-unicode={rust_unicode} excluded={len(result['excluded'])}"
        f" ranges={len(result['ranges'])} py_only={result['py_only']}"
        f" cn_kept={result['cn_kept']}"
    )


def print_diff(old_lines, new_lines, old_name, new_name):
    diff = list(
        difflib.unified_diff(old_lines, new_lines, old_name, new_name, lineterm="")
    )
    for line in diff[:40]:
        print(line)


def without_python_line(text):
    return [l for l in text.splitlines() if not l.startswith("// Python: ")]


def committed_value(text, prefix):
    for line in text.splitlines():
        if line.startswith(prefix):
            return line[len(prefix):]
    return None


def cmd_write_rust_ranges():
    rustc = rustc_version()
    if rustc is None:
        print("gen-word-table: rustc is not on PATH (needed by --write-rust-ranges)")
        return EXIT_NO_RUSTC
    rust_unicode, ranges = run_rust_printer()
    write_data_file(rustc, rust_unicode, ranges)
    print(
        f"gen-word-table: wrote {DATA_REL} ({len(ranges)} ranges, {rustc},"
        f" rust-unicode={rust_unicode})"
    )
    return EXIT_OK


def cmd_write():
    try:
        rustc, rust_unicode, ranges, _ = read_data_file()
    except DataError as e:
        print(f"FAIL: {e}")
        return EXIT_FAIL
    result = sweep(ranges)
    print(summary(rust_unicode, result))
    if result["py_only"] > 0:
        print("FAIL: Python-only code points exist; the table would not be exact")
        return EXIT_FAIL
    TABLE_FILE.write_text(
        render_table(rustc, rust_unicode, result), encoding="utf-8", newline="\n"
    )
    print(f"wrote {TABLE_FILE.relative_to(CRATE.parent.parent)}")
    return EXIT_OK


def cmd_check():
    try:
        rustc, rust_unicode, ranges, _ = read_data_file()
    except DataError as e:
        print(f"gen-word-table: data file {DATA_REL} is malformed")
        print(f"FAIL: {e}")
        return EXIT_FAIL
    result = sweep(ranges)
    print(summary(rust_unicode, result))
    if result["py_only"] > 0:
        print(f"FAIL: {result['py_only']} Python-only code points (must be 0)")
        return EXIT_FAIL
    fresh = render_table(rustc, rust_unicode, result)
    committed = TABLE_FILE.read_text(encoding="utf-8") if TABLE_FILE.exists() else ""
    committed_python = committed_value(committed, "// Python: ")
    if committed_python is not None and committed_python != python_version():
        print(
            f"note: the table was generated by Python {committed_python};"
            f" this is Python {python_version()} (ignored)"
        )
    old = without_python_line(committed)
    new = without_python_line(fresh)
    if old == new and committed.endswith("\n") and "\r" not in committed:
        print("OK")
        return EXIT_OK
    committed_unicode = committed_value(committed, "// Unicode: ")
    if committed_unicode is not None and committed_unicode != unicodedata.unidata_version:
        print(
            f"DRIFT: the committed table was generated with Unicode {committed_unicode};"
            f" this Python has Unicode {unicodedata.unidata_version}"
        )
        print_diff(old, new, "committed word_table.rs", "regenerated word_table.rs")
        return EXIT_DRIFT
    print("FAIL: the committed word_table.rs differs from the regeneration")
    print_diff(old, new, "committed word_table.rs", "regenerated word_table.rs")
    return EXIT_FAIL


def cmd_check_rust():
    rustc = rustc_version()
    if rustc is None:
        print("gen-word-table: rustc is not on PATH (needed by --check-rust)")
        return EXIT_NO_RUSTC
    try:
        _, file_unicode, _, file_lines = read_data_file()
        fresh_unicode, ranges = run_rust_printer()
    except DataError as e:
        print(f"FAIL: {e}")
        return EXIT_FAIL
    fresh_lines = [format_range(s, e) for s, e in ranges]
    print(
        f"gen-word-table --check-rust: rustc={rustc} rust-unicode={fresh_unicode}"
        f" file-rust-unicode={file_unicode} ranges={len(fresh_lines)}"
    )
    if fresh_lines == file_lines:
        print("OK")
        return EXIT_OK
    if fresh_unicode != file_unicode:
        print(
            f"DRIFT: the data file was written with Rust Unicode {file_unicode};"
            f" this rustc has Unicode {fresh_unicode}"
        )
        print_diff(file_lines, fresh_lines, DATA_REL, "fresh rustc ranges")
        return EXIT_DRIFT
    print("FAIL: the data file differs from this rustc under the same Unicode version")
    print_diff(file_lines, fresh_lines, DATA_REL, "fresh rustc ranges")
    return EXIT_FAIL


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write-rust-ranges", action="store_true")
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    group.add_argument("--check-rust", action="store_true")
    args = parser.parse_args()
    if args.write_rust_ranges:
        return cmd_write_rust_ranges()
    if args.write:
        return cmd_write()
    if args.check:
        return cmd_check()
    return cmd_check_rust()


if __name__ == "__main__":
    sys.exit(main())
